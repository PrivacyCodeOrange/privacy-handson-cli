fn get_owner_and_repo_name_from_repo_url(url: &str) -> Option<(String, String)> {
    let Ok(parsed) = Url::parse(url) else {
        return None;
    };

    if parsed.domain() != Some("github.com") {
        return None;
    }
    let Some(segments) = parsed.path_segments() else {
        return None;
    };
    let segments: Vec<&str> = segments.collect();

    if segments.len() < 2 {
        return None;
    }

    let owner = segments[0].to_string();
    let repo = segments[1]
        .strip_suffix(".git")
        .unwrap_or(segments[1])
        .to_string();

    Some((owner, repo))
}

enum PollOutcome {
    Done(String),
    Expired,
    Denied,
}

fn poll_for_token(client_id: &str, device_code: &str, interval: u64) -> PollOutcome {
    loop {
        let data = request_token(client_id, device_code);

        let error = &data["error"].as_str();

        match error {
            None => {}
            Some("authorization_pending") => {
                sleep(Duration::from_secs(interval));
            }
            Some("slow_down") => {
                sleep(Duration::from_secs(interval + 5));
            }
            Some("expired_token") => {
                return PollOutcome::Expired;
            }
            Some("access_denied") => {
                return PollOutcome::Denied;
            }
            _ => {
                panic!("Unexpected response: {}", data);
            }
        }

        if error.is_some() {
            continue;
        }

        let access_token = &data["access_token"].as_str().expect(&format!(
            "`access_token` not found in JSON response: {}",
            data
        ));

        return PollOutcome::Done(access_token.to_string());
    }
}

/* This function was generated by ChatGPT with the prompt
 * `Please give me the rust snippet for asking the user something and they have to type yes/no, or y/n, and the default is no.`
 * */
fn ask_yes_no(prompt: &str) -> io::Result<bool> {
    loop {
        print!("{prompt} [y/N]: ");
        io::stdout().flush()?;

        let mut input = String::new();
        io::stdin().read_line(&mut input)?;

        match input.trim().to_lowercase().as_str() {
            "y" | "yes" => return Ok(true),
            "n" | "no" | "" => return Ok(false),
            _ => println!("Please answer yes or no (y/n)."),
        }
    }
}

fn check_existing_token() -> Option<String> {
    let Ok(token) = storage::load_token() else {
        return None;
    };

    return get_login_id(&token);
}

fn cli_login() -> i32 {
    if let Some(username) = check_existing_token() {
        let msg = format!(
            "There's an already valid token for `{}`. Replace it?",
            username
        );
        match ask_yes_no(&msg) {
            Err(..) | Ok(false) => {
                println!("Previous token was kept");
                return 1;
            }
            Ok(true) => {}
        }
    }
    let DeviceCodeInfo {
        device_code,
        interval,
        user_code,
        verification_uri,
    } = request_device_code(AUTHAPP_CLIENT_ID);

    println!("Please enter from your browser: {}", verification_uri);
    println!("And use the code {}", user_code);

    let outcome = poll_for_token(AUTHAPP_CLIENT_ID, &device_code, interval);
    let access_token = match outcome {
        PollOutcome::Expired => {
            println!("The device code has expired. Please run the login command again.");
            return 1;
        }
        PollOutcome::Denied => {
            println!("Login cancelled by user.");
            return 1;
        }
        PollOutcome::Done(access_token) => access_token,
    };

    storage::save_token(&access_token).unwrap();

    println!("Successfully authenticated!");

    0
}

fn cli_whoami() -> i32 {
    match check_existing_token() {
        Some(username) => {
            println!("Username: {}", username);
            0
        }
        None => {
            println!("Please login first");
            1
        }
    }
}

fn ensure_app_installed(access_token: &str, client_id: &str, app_url: &str) -> bool {
    let client_id = client_id.to_owned();

    let client_ids = get_user_installations_client_ids(access_token);
    if client_ids.contains(&client_id) {
        return true;
    }
    println!(
        "The GitHub app is not installed. Please install it from here on your account: {}",
        app_url
    );

    loop {
        let client_ids = get_user_installations_client_ids(access_token);
        if client_ids.contains(&client_id) {
            return true;
        }

        sleep(Duration::from_secs(5));
    }
}

fn ensure_lab() -> Option<String> {
    match storage::load_current_lab() {
        Ok(lab) => {
            if lab.trim().is_empty() {
                println!("Please choose a lab with the `activate` command");
                None
            } else {
                Some(lab)
            }
        }
        Err(err) => {
            println!("Storage error: {:?}", err);
            None
        }
    }
}

fn cli_create_repo(template_url: &str, new_repo_name: Option<String>) -> i32 {
    let Some(lab) = ensure_lab() else {
        return 1;
    };

    let Some((template_owner, template_repo)) = get_owner_and_repo_name_from_repo_url(template_url)
    else {
        println!("The template url is wrong. Is it a link to a github repository?");
        return 1;
    };
    if !get_repo_is_template(&template_owner, &template_repo) {
        println!(
            "The provided repo is not a template or doesn't exist: `{}`",
            template_url
        );
        return 1;
    }

    let DeviceCodeInfo {
        device_code,
        interval,
        user_code,
        verification_uri,
    } = request_device_code(REPOAPP_CLIENT_ID);

    println!("Please enter from your browser: {}", verification_uri);
    println!("And use the code {}", user_code);

    let outcome = poll_for_token(REPOAPP_CLIENT_ID, &device_code, interval);
    let access_token = match outcome {
        PollOutcome::Expired => {
            println!("The device code has expired. Please run the login command again.");
            return 1;
        }
        PollOutcome::Denied => {
            println!("Login cancelled by user.");
            return 1;
        }
        PollOutcome::Done(access_token) => access_token,
    };

    let Some(this_owner) = get_login_id(&access_token) else {
        println!("Couldn't get login id from github. Try again");
        return 1;
    };

    ensure_app_installed(&access_token, &REPOAPP_CLIENT_ID, &REPOAPP_URL);

    let new_repo_name = match new_repo_name {
        Some(s) => s,
        None => format!("{}-{}-student", template_owner, template_repo),
    };
    let private = true;

    let new_repo_url = format!("https://github.com/{}/{}", this_owner, new_repo_name);

    {
        println!("Create the repository {} ?", new_repo_url);
        match ask_yes_no("Approve repository creation") {
            Err(..) | Ok(false) => {
                println!("The repository wasn't created");
                return 1;
            }
            Ok(true) => {}
        }
    }

    let res = generate_repo_from_template(
        &access_token,
        &template_owner,
        &template_repo,
        &this_owner,
        &new_repo_name,
        private,
    );
    let Ok((_full_name, html_url)) = res else {
        match res {
            Err(RepoAlreadyExistsError) => {
                println!("The repository already exists: `{}`", new_repo_url);
            }
            Ok(..) => {}
        }
        return 1;
    };

    println!("Created private repository: {}", html_url);

    storage::add_repository(&html_url, &lab).unwrap();

    0
}

fn cli_activate(lab: &str) -> i32 {
    if !AVAILABLE_LABS.contains(&lab) {
        println!(
            "Lab {} doesn't exist. Available labs: {:?}",
            lab, AVAILABLE_LABS
        );
        return 1;
    }

    storage::save_current_lab(lab).unwrap();

    println!("Lab activated: {}", lab);

    0
}

fn cli(args: Args) -> i32 {
    match args.command {
        Command::Login => cli_login(),
        Command::Whoami => cli_whoami(),
        Command::Createrepo { template_url, name } => cli_create_repo(&template_url, name),
        Command::Activate { lab } => cli_activate(&lab),
    }
}

fn main() {
    let args = Args::parse();

    exit(cli(args));
}
